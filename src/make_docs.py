"""Generate the number-carrying docs from artifacts/metrics.json.

    python -m src.make_docs        (train.py also runs this automatically)

Writes:
  docs/PRD_reconciliation.md   - PRD claim vs measured value
  docs/DEFENSE_CHEAT_SHEET.md  - one-sentence answers + demo script
  README.md                    - only the block between the RESULTS markers

Every measured number comes from metrics.json, which train.py computes from
the data. The only typed numbers here are the PRD's *claims*, kept so they can
be compared with what was measured.
"""
from __future__ import annotations

import json

from src import config

DOCS_DIR = config.ROOT_DIR / "docs"
README = config.ROOT_DIR / "README.md"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"

# What the PRD claimed (claims, not results).
PRD_CLAIMS = {
    "silhouette_k3": 0.292,
    "sizes": {"Full-Price Loyal": 1918, "Discount-Driven Regular": 1443,
              "High-Frequency Shoppers": 539},
}


def _load() -> dict:
    return json.loads(config.METRICS_PATH.read_text())


def _sweep(fs: dict) -> dict[int, dict]:
    return {r["k"]: r for r in fs["sweep"]}


def _sizes(sizes: dict) -> str:
    return " / ".join(f"{k} {v:,}" for k, v in
                      sorted(sizes.items(), key=lambda kv: -kv[1]))


def _labels(top: dict) -> str:
    """'Weekly (539)' style list of the frequency labels in a segment."""
    return " + ".join(f"{k} ({v:,})" for k, v in top["labels"].items()) + " buyers"


def sweep_table(m: dict) -> str:
    names = list(m["feature_sets"])
    lines = ["| k | " + " | ".join(f"`{n}`" for n in names) + " |",
             "|---|" + "---|" * len(names)]
    for k in config.K_RANGE:
        cells = []
        for n in names:
            fs = m["feature_sets"][n]
            v = _sweep(fs)[k]["silhouette"]
            mark = " ◀ elbow" if fs["elbow_k"] == k else ""
            bold = n == m["chosen"]["feature_set"] and k == m["chosen"]["k"]
            cells.append(f"**{v:.3f}**{mark}" if bold else f"{v:.3f}{mark}")
        lines.append(f"| {k} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def rule_table(m: dict) -> str:
    lines = ["| Feature set | Features | Elbow k | Silhouette at elbow | Smallest "
             "segment | Eligible | Passes gate | Segment sizes at k=3 |",
             "|---|---|---|---|---|---|---|---|"]
    for n, fs in m["feature_sets"].items():
        lines.append(
            f"| `{n}` | {', '.join(fs['features'])} | {fs['elbow_k']} | "
            f"{fs['silhouette_at_elbow']:.3f} | {fs['min_cluster_share_at_elbow']:.1%} | "
            f"{'yes' if fs['eligible'] else 'no (all discrete)'} | "
            f"{'yes' if fs['passes_gate'] else 'no'} | {_sizes(fs['segment_sizes_at_k3'])} |")
    return "\n".join(lines)


def profile_table(m: dict) -> str:
    lines = ["| Segment | Customers | % of base | Purchases/yr | Avg spend | "
             "Discount use | Subscribers | Plain English |",
             "|---|---|---|---|---|---|---|---|"]
    for p in m["segment_profile"]:
        lines.append(
            f"| {p['segment']} | {p['customers']:,} | {p['pct_of_base']:.1f}% | "
            f"{p['avg_purchase_rate_per_year']:.1f} | ${p['avg_spend']:.2f} | "
            f"{p['discount_usage_pct']:.0f}% | {p['subscriber_pct']:.0f}% | "
            f"{p['description']} |")
    return "\n".join(lines)


def how_k_sentence(m: dict) -> str:
    ch = m["chosen"]
    return (
        "We fixed a rule in `config.py` and applied it to every feature set: take the "
        "elbow of the inertia curve (Kneedle method), accept it only if silhouette ≥ "
        f"{config.MIN_SILHOUETTE} and every segment holds ≥ {config.MIN_CLUSTER_SHARE:.0%} "
        "of customers, ignore feature sets made only of discrete values (their "
        "silhouette is inflated), and keep the highest silhouette. That selected "
        f"**{', '.join(ch['features'])}** with **k = {ch['k']}** "
        f"(silhouette **{ch['silhouette']:.3f}**).")


def key_numbers(m: dict) -> dict:
    prd = m["feature_sets"][config.PRIMARY_FEATURE_SET]
    sw = _sweep(prd)
    best_k = max(sw, key=lambda k: sw[k]["silhouette"])
    return {"prd_sil_k3": sw[3]["silhouette"], "prd_best_k": best_k,
            "prd_best_sil": sw[best_k]["silhouette"], "prd_elbow": prd["elbow_k"],
            "prd_sizes_k3": prd["segment_sizes_at_k3"]}


# ---------------------------------------------------------------------------
# Documents
# ---------------------------------------------------------------------------
def results_block(m: dict) -> str:
    ch = m["chosen"]
    s = m["surrogate_tree"]
    return f"""{START}
<!-- This block is generated by `python -m src.make_docs` from artifacts/metrics.json. Do not edit by hand. -->

**Chosen model:** `{ch['feature_set']}` = {', '.join(ch['features'])} · **k = {ch['k']}** ·
**silhouette = {ch['silhouette']:.3f}** · trained on {m['n_rows']:,} rows.

**How k was picked (say this in the viva):** {how_k_sentence(m)}

**Silhouette for every feature set and k** (bold = chosen, ◀ = elbow):

{sweep_table(m)}

**Selection rule applied to each feature set:**

{rule_table(m)}

**Segment profile (final model):**

{profile_table(m)}

**Surrogate explanation:** a depth-{config.SURROGATE_MAX_DEPTH} decision tree imitates the
clusters with {s['fidelity']:.1%} agreement; feature importances:
{', '.join(f"{k} {v:.2f}" for k, v in sorted(s['feature_importances'].items(), key=lambda kv: -kv[1]))}.
{END}"""


def reconciliation(m: dict) -> str:
    kn = key_numbers(m)
    ch = m["chosen"]
    facts = m["data_facts"]
    bw = m["bi_weekly_sensitivity"]
    chosen_k3 = m["feature_sets"][ch["feature_set"]]["profile_at_k3"]
    k3_rows = "\n".join(
        f"| {p['segment']} | {p['customers']:,} | {p['purchase_rate_per_year']:.1f} | "
        f"${p['avg_spend']:.2f} | {p['discount_usage_pct']:.0f}% |" for p in chosen_k3)
    return f"""# PRD reconciliation — claims vs. measured values

> Generated by `python -m src.make_docs` from `artifacts/metrics.json`.
> Every "measured" value is computed by the code from `data/Customer_dataset.csv`.

## Claim vs. measurement

| PRD claim | PRD value | Measured | Verdict |
|---|---|---|---|
| Silhouette at k=3 with the 4 PRD features | {PRD_CLAIMS['silhouette_k3']} | {kn['prd_sil_k3']:.3f} | does not reproduce |
| Silhouette peaks at k=3 (4 features) | k=3 | highest at k={kn['prd_best_k']} ({kn['prd_best_sil']:.3f}) | does not reproduce |
| Elbow flattens at k=3 (4 features) | k=3 | Kneedle elbow at k={kn['prd_elbow']} | does not reproduce |
| Segment sizes from the 4 PRD features | {_sizes(PRD_CLAIMS['sizes'])} | {_sizes(kn['prd_sizes_k3'])} | different split (by discount/spend, not frequency) |
| The same sizes exist for some feature set | — | `{ch['feature_set']}` at k=3: {_sizes(m['feature_sets'][ch['feature_set']]['segment_sizes_at_k3'])} | reproduces with 3 features (no previous_purchases) |
| Final segmentation | 3 segments | {ch['k']} segments, silhouette {ch['silhouette']:.3f} | chosen by the written rule |

The PRD's three segments at k=3 with `{ch['feature_set']}` (measured):

| Segment | Customers | Purchases/yr | Avg spend | Discount use |
|---|---|---|---|---|
{k3_rows}

## Why the numbers differ

* **The data has almost no correlation between features** (largest |r| between the four
  PRD features = {facts['max_abs_correlation_between_features']:.3f}). Spend and previous purchases
  are spread evenly, so they add noise rather than cluster structure. Adding
  `previous_purchases` (the 4-feature design) dilutes the frequency/discount structure.
* **Two features are discrete.** `discount_flag` has {facts['distinct_values']['discount_flag']} values and
  `purchase_rate_per_year` has {facts['distinct_values']['purchase_rate_per_year']}. With only discrete features the
  rows sit on a handful of points, so silhouette keeps rising with k and never "peaks".
  That is why the rule excludes all-discrete feature sets, and why elbow + silhouette is
  treated as a heuristic here, not proof.
* `Weekly` alone is exactly {facts['weekly_rows']:,} rows, which is why that segment size appears so reliably.

## How the final choice was made (and what was *not* done)

* The rule (in `src/config.py`) was written after the exploratory silhouette tables had been
  seen (you had already run them), **but before** the elbows were computed and before knowing
  which feature set or k it would select. It was not adjusted afterwards.
* Nothing was tuned towards 0.292. The PRD's 4-feature design is still reported in full
  as the primary experiment.
* Business interpretability is part of the rule only through the eligibility step (no
  all-discrete sets) and the minimum segment size; the final pick is the highest silhouette.

## Bi-Weekly sensitivity

`Bi-Weekly` is ambiguous (every two weeks = 26/yr, twice a week = 104/yr). Default: 26.
Re-running everything with 104: chosen set `{bw['chosen_feature_set']}`, k = {bw['chosen_k']},
silhouette {bw['silhouette']:.3f}, sizes {_sizes(bw['segment_sizes'])}. Agreement with the default segments
(adjusted Rand index) = {bw['adjusted_rand_index_vs_default']:.2f}, so **the choice
{'does not change' if bw['same_segments'] else 'does change'} the segments**. The highest-rate segment
("{bw['top_rate_segment_default']['segment']}") contains {_labels(bw['top_rate_segment_default'])} with 26/yr, but
{_labels(bw['top_rate_segment_104'])} with 104/yr. Keep 26 unless the business confirms "twice a week".

## What to say in the defense

1. "The PRD's 0.292 did not reproduce. With the four PRD features we measured
   {kn['prd_sil_k3']:.3f} at k=3, and it does not peak at k=3. The measured numbers are what the app shows."
2. "So we compared four feature sets with a written selection rule instead of picking k by eye."
3. "{how_k_sentence(m).replace('**', '')}"
4. "The PRD's three segments are what this feature set gives at k=3; k={ch['k']} splits the two large groups
   by spend, which is more useful for targeting."
5. "Elbow and silhouette are heuristics, especially with discrete features — we say so openly."
"""


def cheat_sheet(m: dict) -> str:
    ch = m["chosen"]
    segs = ", ".join(p["segment"] for p in m["segment_profile"])
    return f"""# Defense cheat sheet

> Generated by `python -m src.make_docs` from `artifacts/metrics.json`.

## The mentor's two concerns — one sentence each

* **Generalizability:** "The hand-written New/Returning/Loyal rule is gone: K-Means discovers
  the groups from the data, a written rule picks k, and the same pipeline re-learns segments on
  any uploaded file (page 4, Mode B) — the *method* generalizes, the specific segments do not."
* **Third-party benefit:** "Anyone can open the web app, upload their own CSV (any column
  names — the mapper matches them), and download their customers with segment labels and a
  dashboard, without writing code."

## Likely questions

* **How did you pick k?** {how_k_sentence(m)}
* **Why K-Means?** Simple, fast, easy to explain (each segment = its average customer),
  standard for customer segmentation, and the centres make labelling and prediction trivial.
* **Why scale the features?** K-Means uses distances; without `StandardScaler` the feature with
  the biggest numbers (spend in dollars) would dominate.
* **How are segments named?** Automatically, from each cluster's average compared with the
  overall average (z-scores) — e.g. high purchase rate → "High-Frequency". No hand-picked names.
* **Why did the PRD numbers change?** See `PRD_reconciliation.md`: the 4-feature design gives
  silhouette {key_numbers(m)['prd_sil_k3']:.3f} at k=3, not 0.292, so we report measured values only.
* **Current segments:** {segs}.

## Limits (say them before you are asked)

* The frozen model (page 2 / Mode A) **force-fits** foreign data into the retail segments;
  the app warns when an upload looks different. Mode B avoids this by re-learning.
* Small feature set (purchase rate, spend, discount); the data has no dates or baskets.
* K-Means assumes roughly round, similar-sized clusters; weak silhouette = weak segments.
* Findings are specific to this dataset; only the pipeline generalizes.
* One file at a time (no joins); needs at least 2 numeric features.
* Free Streamlit hosting is best-effort, fine for a demo, not production.

## How it generalizes

* **Column mapper:** suggests which column is amount/date/customer etc. (synonyms, fuzzy
  matching, data-type sniffing) — files with different column names work.
* **Mode B — Fit on my data:** the same k-sweep, the same rule, the same auto-labelling on any
  file, so nothing is force-fitted.
* **RFM:** transaction files (many rows per customer, with dates) become one row per customer
  (recency, frequency, monetary) before clustering.
* **Adaptive dashboard:** charts appear only for columns the file has.

## 5-minute live demo script

1. **Overview Dashboard (1 min):** KPIs, revenue by category/age group, then the segment donut.
   Open *Model validation*: show the sweep table and say the "how did you pick k" sentence.
2. **Upload & Predict (1 min):** tick *Use sample dataset* → segments appear → *Download results*.
   Point at the blue "model is frozen" box.
3. **Segment Explorer (30 s):** filter Segment = High-Frequency, Gender = Female; show the
   filtered-vs-all comparison.
4. **Analyze Your Data (2 min):** choose *Sample: transactions* — show the mapper guessing
   `cust_id`, `invoice_date`, `order_total` with green badges → RFM message → *Run segmentation*
   → elbow/silhouette, chosen k, PCA, named segments (e.g. Champions, Dormant) → dashboard with
   a monthly trend.
5. **Close (30 s):** "Same pipeline, any file. The numbers on screen are computed live; the PRD
   numbers that did not reproduce are documented in the reconciliation."
"""


def main() -> None:
    m = _load()
    DOCS_DIR.mkdir(exist_ok=True)
    (DOCS_DIR / "PRD_reconciliation.md").write_text(reconciliation(m))
    (DOCS_DIR / "DEFENSE_CHEAT_SHEET.md").write_text(cheat_sheet(m))
    if README.exists():
        text = README.read_text()
        if START in text and END in text:
            before, rest = text.split(START, 1)
            _, after = rest.split(END, 1)
            README.write_text(before + results_block(m) + after)
    print("Docs written: docs/PRD_reconciliation.md, docs/DEFENSE_CHEAT_SHEET.md"
          + (", README results block" if README.exists() else ""))


if __name__ == "__main__":
    main()
